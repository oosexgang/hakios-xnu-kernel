#!/usr/bin/env python3
"""
Pull one area out of the touch controller's firmware image and write it as C.

  mktouchfw.py <hdl_firmware.img> <AREA_NAME> <out.h>

The controller keeps its firmware in RAM and loses it whenever it is reset, which a reboot does;
the loader therefore carries the firmware itself and sends it over SPI before it starts the kernel.
The image is a header -- a magic, a count, then an offset per area -- and each area is a 36-byte
descriptor followed by its contents. Besides the area itself the script writes TOUCH_FW_FLAG, the
u16 the controller's driver packs out of the descriptor's identity field at +0x18: the ROMBOOT
download leads the area with 14 header bytes whose byte 0 is that flag's low byte.
"""
import struct
import sys

IMAGE_MAGIC = 0x4818472b
AREA_MAGIC = 0x7c05e516
DESCRIPTOR = 36


def area(data, name):
    magic, count = struct.unpack_from('<2I', data, 0)
    if magic != IMAGE_MAGIC:
        raise SystemExit('not a touch firmware image')
    for i in range(count):
        at, = struct.unpack_from('<I', data, 8 + i * 4)
        if struct.unpack_from('<I', data, at)[0] != AREA_MAGIC:
            continue
        if data[at + 4:at + 20].split(b'\0')[0].strip() != name.encode():
            continue
        length, = struct.unpack_from('<I', data, at + 28)
        return (data[at + DESCRIPTOR:at + DESCRIPTOR + length],
                data[at + 0x18:at + 0x1c])          # identity field, the flag is built of it
    raise SystemExit('no area called %s in the image' % name)


def main():
    if len(sys.argv) != 4:
        raise SystemExit(__doc__.strip())
    image, name, out = sys.argv[1], sys.argv[2], sys.argv[3]
    blob, identity = area(open(image, 'rb').read(), name)
    # The controller's own driver packs the identity field lossily, bits 1, 9, 17 and 19, and
    # only the low half of the result travels -- as byte 0 of the ROMBOOT download's 14-byte
    # header. A value it cannot recover is not one the chip needs either.
    flag = ((identity[0] << 1) | (identity[1] << 9) |
            (identity[2] << 17) | ((identity[3] & 0x7f) << 19)) & 0xffff
    with open(out, 'w') as f:
        f.write('/* Generated by tools/mktouchfw.py from %s, area %s. Do not edit. */\n'
                % (image.split('/')[-1], name))
        f.write('#ifndef TOUCHFW_H\n#define TOUCHFW_H\n\n#include <stdint.h>\n\n')
        f.write('#define TOUCH_FW_SIZE %du\n#define TOUCH_FW_FLAG 0x%04xu\n\n'
                'static const uint8_t touch_fw[TOUCH_FW_SIZE] = {\n'
                % (len(blob), flag))
        for i in range(0, len(blob), 16):
            f.write('\t' + ' '.join('0x%02x,' % b for b in blob[i:i + 16]) + '\n')
        f.write('};\n\n#endif /* TOUCHFW_H */\n')
    print('%s: %d bytes, flag 0x%04x, from %s' % (out, len(blob), flag, name))


main()
