#!/usr/bin/env python3
"""
Make mtkloader/camrx.h, the camera receiver's register table, from two things of your own phone's:
  - a dump of the live registers while the camera HAL streams (logs/camera/auto_dump.sh -> regs_auto_rear/), and
  - the receiver as the hardware leaves it after reset (the CAM_SYS stage's log, logs/camera/cam-probe-sys*.log).
The table is the registers whose value Android changed (SENINF) plus the analog block of the port in use, in the
order the loader writes them. It is the vendor's tuning, made on your machine, never kept in git (.gitignore).

  tools/camrx.py [live-dir] [reset-log] [out.h]
"""
import re
import struct
import sys

LIVE = sys.argv[1] if len(sys.argv) > 1 else "logs/camera/regs_auto_rear"
RESET = sys.argv[2] if len(sys.argv) > 2 else "logs/camera/cam-probe-sys2.log"
OUT = sys.argv[3] if len(sys.argv) > 3 else "mtkloader/camrx.h"

SENINF = 0x1A040000
MIPI = 0x11C10000
PORT_BLOCKS = (2, 3)            # csi1a and csi1b: the analog blocks the live registers show in use
LATE = (0x0008, 0x0020, 0x2A00)  # written last: the top mux, the top control, the CSI-2 port's own control
STATUS_ONLY = ()                 # nothing is left out: a read-only register ignores the write


def words(path):
    d = open(path, "rb").read()
    return {i * 4: v for i, v in enumerate(struct.unpack("<%dI" % (len(d) // 4), d))}


def reset_seninf(path):
    txt = open(path, errors="replace").read()
    sec = txt[txt.index("reading SENINF page 0x0"):txt.index("reading CAMSV0")]
    return {int(m.group(1), 16): int(m.group(2), 16) for m in re.finditer(r"\+0x([0-9a-f]+) = 0x([0-9a-f]+)", sec)}


SV1 = 0x1A051000
SV_BUF = 0x60000000                 # where the CAMSV DMA is told to write: plain DRAM, clear of the reserved zones
SV_ADDR_REGS = {0x118: SV_BUF, 0x11C: SV_BUF + 0x500000, 0xE04: SV_BUF + 0x200000}   # Android's 0x4d600000, 0x4db00000, 0x4d800000
SV_SKIP = (0x2C, 0x118, 0x11C, 0xE04)   # the queue's own: the loader enqueues buffers as the HAL does (addresses first, then the ready bit); +0x11c is the hardware's
SV_UNUSED = ()                        # (+0x114 must stay: without it nothing is written at all, header included -- it enables the frame buffer queue)
SV_LATE = (0x500, 0x504)            # the sensor interface and the view-finder enable, last


def reset_camsv1(path):
    txt = open(path, errors="replace").read()
    i = txt.index("CAMSV1 0x1a051000")
    sec = txt[i:txt.index("closing the gates again") if "closing the gates again" in txt[i:] else txt.index("receiver read")]
    return {int(m.group(1), 16): int(m.group(2), 16) for m in re.finditer(r"\+0x([0-9a-f]+) = 0x([0-9a-f]+)", sec)}


def main():
    live = words(LIVE + "/1a040000_8000.bin")
    mipi = words(LIVE + "/11c10000_6000.bin")
    rst = reset_seninf(RESET)
    regs = []
    # 1. the analog block of the port in use, as the HAL left it (every non-zero word)
    for b in PORT_BLOCKS:
        for off in range(0, 0x1000, 4):
            v = mipi[b * 0x1000 + off]
            if v:
                regs.append((MIPI + b * 0x1000 + off, v, "mipi %d" % b))
    # 2. SENINF: what differs from reset, in address order, the late ones kept back
    diffs = [o for o in sorted(set(live) | set(rst)) if live.get(o, 0) != rst.get(o, 0) and o < 0x8000]
    for o in diffs:
        if o not in LATE:
            regs.append((SENINF + o, live.get(o, 0), "seninf"))
    for o in LATE:
        if live.get(o, 0) != rst.get(o, 0):
            regs.append((SENINF + o, live[o], "seninf late"))
    sv_live = words(LIVE + "/1a051000_1000.bin")
    sv_rst = reset_camsv1(RESET)
    sv = []
    for o in sorted(set(sv_live) | set(sv_rst)):
        if o in SV_LATE or o in SV_SKIP or sv_live.get(o, 0) == sv_rst.get(o, 0):
            continue
        v = SV_ADDR_REGS.get(o, sv_live.get(o, 0))
        sv.append((SV1 + o, v, "camsv1"))
    for o in SV_LATE:
        sv.append((SV1 + o, sv_live.get(o, 0), "camsv1 late"))
    with open(OUT, "w") as f:
        f.write("/* Generated by tools/camrx.py from a live dump (%s) and the reset-state read (%s).\n" % (LIVE, RESET))
        f.write(" * The vendor's tuning, made on your machine, never kept in git (.gitignore). */\n")
        f.write("#define CAM_RX_N %d\n" % len(regs))
        f.write("static const struct { uint64_t addr; uint32_t val; } cam_rx_table[CAM_RX_N] = {\n")
        for a, v, why in regs:
            f.write("\t{ 0x%08x, 0x%08x },   /* %s */\n" % (a, v, why))
        f.write("};\n")
        f.write("#define CAM_RX_BUF 0x%08xULL\n" % SV_BUF)
        f.write("#define CAM_RX_SV_N %d\n" % len(sv))
        f.write("static const struct { uint64_t addr; uint32_t val; } cam_rx_sv_table[CAM_RX_SV_N] = {\n")
        for a, v, why in sv:
            f.write("\t{ 0x%08x, 0x%08x },   /* %s */\n" % (a, v, why))
        f.write("};\n")
    print("CAMSV_1: %d registers" % len(sv))
    print("%s: %d registers (%d analog, %d SENINF)" % (OUT, len(regs), sum(1 for r in regs if r[2].startswith("mipi")),
                                                       sum(1 for r in regs if r[2].startswith("seninf"))))


if __name__ == "__main__":
    main()
