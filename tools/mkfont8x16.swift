// Rasterize printable ASCII from Menlo into an 8x16 1-bit font, emitted as a C header.
// Usage: swift tools/mkfont8x16.swift > mtkloader/font8x16.h
import CoreGraphics
import CoreText
import Foundation

let W = 8, H = 16
let font = CTFontCreateWithName("Menlo-Bold" as CFString, 13, nil)


print("/* Generated by tools/mkfont8x16.swift: Menlo Bold 13pt, ASCII 0x20-0x7e, 8x16, MSB = left. */")
print("static const unsigned char font8x16[95][16] = {")
for code in 0x20...0x7e {
    let ctx = CGContext(data: nil, width: W, height: H, bitsPerComponent: 8, bytesPerRow: W,
                        space: CGColorSpaceCreateDeviceGray(), bitmapInfo: CGImageAlphaInfo.none.rawValue)!
    ctx.setFillColor(gray: 0, alpha: 1)
    ctx.fill(CGRect(x: 0, y: 0, width: W, height: H))
    ctx.setAllowsAntialiasing(true)
    var ch = UniChar(code)
    var glyph = CGGlyph(0)
    CTFontGetGlyphsForCharacters(font, &ch, &glyph, 1)
    ctx.setFillColor(gray: 1, alpha: 1)
    var pos = CGPoint(x: 0, y: 4)
    CTFontDrawGlyphs(font, &glyph, &pos, 1, ctx)
    let px = ctx.data!.assumingMemoryBound(to: UInt8.self)
    var rows: [String] = []
    for y in 0..<H {
        var b = 0
        for x in 0..<W where px[y * W + x] > 100 { b |= 0x80 >> x }
        rows.append(String(format: "0x%02x", b))
    }
    let c = code == 0x5c ? "backslash" : (code == 0x2a ? "asterisk" : String(UnicodeScalar(UInt8(code))))
    print("    { \(rows.joined(separator: ",")) }, /* \(c) */")
}
print("};")
