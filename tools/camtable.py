#!/usr/bin/env python3
"""
Make mtkloader/camjn1.h, the S5K JN1's register table, from a capture of Android bringing the camera up
(logs/camera/capture.sh on the phone, then the file it pulls). The table is the vendor's, so it is made on your
machine from your phone's own capture and is never kept in git (.gitignore), like mtkloader's touchfw.h.

  tools/camtable.py [logs/camera/cam_all.txt] [mtkloader/camjn1.h]

What it takes: every write Android made to the sensor (I2C write id 0x20) between the two ID reads and the write that
starts streaming (register 0x0100 <- 1), in order. A burst Android sent as one table (iBurstWriteReg_multi) is a run
of 4-byte "register, value" pairs and becomes that many writes. The pauses between writes are kept (the sensor needs
some: after its soft reset, for one), less what a write itself takes, and capped.
"""
import re
import struct
import sys

SENSOR_ID = 0x20            # the 8-bit write address of the main camera's sensor
TRANSFER_US = 500           # roughly what one write costs the loader; a pause is counted from beyond it
MIN_GAP_US = 800            # shorter gaps between Android's writes are just its own speed
MAX_PAUSE_US = 250000


def parse(path):
    events = []
    bursts_tail = {}
    for line in open(path, errors="replace"):
        m = re.match(r"^\s*(\S+?)-(\d+)\s+\[\d+\]\s+\S+\s+(\d+\.\d+): (wr|rd|bwa|bwb): \(.*?\) (.*)$", line)
        if not m:
            continue
        _, pid, ts, kind, rest = m.groups()
        kv = {k: int(v, 0) for k, v in re.findall(r"(\w+)=(0x[0-9a-f]+|\d+)", rest)}
        if (kv.get("id", 0) & 0xFFFF) != SENSOR_ID:
            continue
        ts = float(ts)
        if kind == "bwb":
            bursts_tail[(pid, round(ts, 3))] = kv
        elif kind == "bwa":
            events.append((ts, "B", (pid, kv)))
        else:
            data = bytes(kv.get("b%d" % i, 0) & 0xFF for i in range(8))
            size = (kv.get("sz", kv.get("ssz", 0))) & 0xFFFF
            events.append((ts, "W" if kind == "wr" else "R", data[:size]))
    events.sort(key=lambda e: e[0])
    return events, bursts_tail


def burst_bytes(pid, kv, tails, ts):
    size = kv["sz"] & 0xFFFF
    data = b"".join(struct.pack("<Q", kv["w%d" % i]) for i in range(126) if "w%d" % i in kv)
    for (p, t), tv in tails.items():
        if p == pid and abs(t - ts) < 0.002:
            data += struct.pack("<Q", tv["t0"]) + struct.pack("<Q", tv["t1"])
            break
    return data[:size]


def main():
    src = sys.argv[1] if len(sys.argv) > 1 else "logs/camera/cam_all.txt"
    dst = sys.argv[2] if len(sys.argv) > 2 else "mtkloader/camjn1.h"
    events, tails = parse(src)
    if not events:
        sys.exit("no writes to the sensor (id 0x20) in %s" % src)
    # the first write after the ID reads ... up to (not including) the write that starts the stream
    first = next(i for i, e in enumerate(events) if e[1] == "W")
    stream = next(i for i, e in enumerate(events)
                  if e[1] == "W" and len(e[2]) == 3 and e[2] == b"\x01\x00\x01")
    ops = []        # [register, value, width in bytes, pause after in us]
    for i in range(first, stream):
        ts, kind, data = events[i]
        gap_us = int((events[i + 1][0] - ts) * 1e6)
        pause = gap_us - TRANSFER_US if gap_us >= MIN_GAP_US else 0
        pause = min(max(pause, 0), MAX_PAUSE_US)
        if kind == "W":
            reg = data[0] << 8 | data[1]
            if len(data) == 4:
                ops.append([reg, data[2] << 8 | data[3], 2, pause])
            elif len(data) == 3:
                ops.append([reg, data[2], 1, pause])
            else:
                sys.exit("a write of %d bytes at +%.3f s: not understood" % (len(data), ts - events[0][0]))
        elif kind == "B":
            pid, kv = data
            raw = burst_bytes(pid, kv, tails, ts)
            if len(raw) % 4:
                sys.exit("a burst of %d bytes is not a run of 4-byte pairs" % len(raw))
            pairs = [(raw[j] << 8 | raw[j + 1], raw[j + 2] << 8 | raw[j + 3]) for j in range(0, len(raw), 4)]
            for k, (reg, val) in enumerate(pairs):
                ops.append([reg, val, 2, pause if k == len(pairs) - 1 else 0])
        # reads in the sequence are not replayed; their time is in the pause of the write before them
    with open(dst, "w") as out:
        out.write("/* Generated by tools/camtable.py from %s: the S5K JN1's registers as Android wrote them,\n" % src)
        out.write(" * in order, between the ID reads and the write that starts the stream. The vendor's data: made on\n")
        out.write(" * your machine from your phone's own capture, never kept in git (.gitignore). */\n")
        out.write("#define CAM_JN1_OPS %d\n" % len(ops))
        out.write("static const struct { uint16_t reg, val; uint8_t width; uint32_t pause_us; } cam_jn1_table[CAM_JN1_OPS] = {\n")
        for reg, val, width, pause in ops:
            out.write("\t{ 0x%04x, 0x%04x, %d, %d },\n" % (reg, val, width, pause))
        out.write("};\n")
    total = sum(p for _, _, _, p in ops)
    print("%s: %d writes (%d of them single-byte), pauses add up to %.0f ms" %
          (dst, len(ops), sum(1 for o in ops if o[2] == 1), total / 1000))


if __name__ == "__main__":
    main()
