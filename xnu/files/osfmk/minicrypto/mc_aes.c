/* Returns a description of the first failing check, or NULL if all pass. */
const char *
mc_aes_selftest(void)
{
	static const uint8_t key[32] = { 0x00, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07, 0x08, 0x09, 0x0a, 0x0b, 0x0c, 0x0d, 0x0e, 0x0f, 0x10, 0x11, 0x12, 0x13, 0x14, 0x15, 0x16, 0x17, 0x18, 0x19, 0x1a, 0x1b, 0x1c, 0x1d, 0x1e, 0x1f };
	static const uint8_t iv[16] = { 0xf0, 0xf1, 0xf2, 0xf3, 0xf4, 0xf5, 0xf6, 0xf7, 0xf8, 0xf9, 0xfa, 0xfb, 0xfc, 0xfd, 0xfe, 0xff };
	static const uint8_t plain[48] = { 0x00, 0x11, 0x22, 0x33, 0x44, 0x55, 0x66, 0x77, 0x88, 0x99, 0xaa, 0xbb, 0xcc, 0xdd, 0xee, 0xff, 0x6b, 0xc1, 0xbe, 0xe2, 0x2e, 0x40, 0x9f, 0x96, 0xe9, 0x3d, 0x7e, 0x11, 0x73, 0x93, 0x17, 0x2a, 0xae, 0x2d, 0x8a, 0x57, 0x1e, 0x03, 0xac, 0x9c, 0x9e, 0xb7, 0x6f, 0xac, 0x45, 0xaf, 0x8e, 0x51 };
	static const uint8_t ecb128[16] = { 0x69, 0xc4, 0xe0, 0xd8, 0x6a, 0x7b, 0x04, 0x30, 0xd8, 0xcd, 0xb7, 0x80, 0x70, 0xb4, 0xc5, 0x5a };   /* FIPS 197 C.1 */
	static const uint8_t ecb256[16] = { 0x8e, 0xa2, 0xb7, 0xca, 0x51, 0x67, 0x45, 0xbf, 0xea, 0xfc, 0x49, 0x90, 0x4b, 0x49, 0x60, 0x89 };   /* FIPS 197 C.3 */
	static const uint8_t cbc128[48] = { 0x77, 0x02, 0xfc, 0x9b, 0x71, 0xc6, 0x3d, 0x26, 0xa2, 0xf0, 0x9d, 0xf5, 0xc4, 0x45, 0x10, 0x2a, 0x12, 0x4e, 0x7d, 0x18, 0xd9, 0x0f, 0xb7, 0x68, 0x47, 0x71, 0xd3, 0xb9, 0x5b, 0x9b, 0x45, 0xcd, 0x56, 0x95, 0x95, 0xd6, 0xeb, 0x0c, 0x39, 0x43, 0x74, 0xf8, 0x70, 0x7e, 0xa5, 0x3e, 0xe7, 0x03 };      /* OpenSSL */
	static const uint8_t ctr256[40] = { 0x92, 0x11, 0xef, 0xbe, 0x67, 0xc3, 0xe6, 0xbc, 0xd2, 0xf0, 0x4c, 0xef, 0x8c, 0xef, 0x8d, 0xeb, 0xa1, 0x9e, 0xc5, 0xa2, 0xdf, 0x6a, 0xab, 0x57, 0x87, 0x9a, 0x2b, 0x30, 0x39, 0xe4, 0x91, 0xa4, 0x37, 0x41, 0xab, 0x0c, 0x0a, 0x1b, 0x59, 0x04 };      /* OpenSSL */
	struct mc_aes_key k;
	struct mc_aes_ctr c;
	uint8_t chain[16], out[48];

	mc_aes_setkey(&k, 16, key);
	mc_aes_encrypt_block(&k, plain, out);
	if (memcmp(out, ecb128, 16) != 0) {
		return "aes-128 encrypt";
	}
	mc_aes_decrypt_block(&k, ecb128, out);
	if (memcmp(out, plain, 16) != 0) {
		return "aes-128 decrypt";
	}
	mc_aes_setkey(&k, 32, key);
	mc_aes_encrypt_block(&k, plain, out);
	if (memcmp(out, ecb256, 16) != 0) {
		return "aes-256 encrypt";
	}
	mc_aes_decrypt_block(&k, ecb256, out);
	if (memcmp(out, plain, 16) != 0) {
		return "aes-256 decrypt";
	}

	mc_aes_setkey(&k, 16, key);
	memcpy(chain, iv, 16);
	mc_cbc_encrypt((const cccbc_ctx *)&k, (cccbc_iv *)chain, 3, plain, out);
	if (memcmp(out, cbc128, 48) != 0) {
		return "aes-128-cbc encrypt";
	}
	memcpy(chain, iv, 16);
	mc_cbc_decrypt((const cccbc_ctx *)&k, (cccbc_iv *)chain, 3, out, out); /* in place */
	if (memcmp(out, plain, 48) != 0) {
		return "aes-128-cbc decrypt";
	}

	mc_ctr_init(&mc_aes_ctr_crypt, (ccctr_ctx *)&c, 32, key, iv);
	mc_ctr_crypt((ccctr_ctx *)&c, 7, plain, out);          /* uneven pieces */
	mc_ctr_crypt((ccctr_ctx *)&c, 33, plain + 7, out + 7);
	if (memcmp(out, ctr256, 40) != 0) {
		return "aes-256-ctr";
	}
	return NULL;
}
